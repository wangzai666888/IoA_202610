"""Generate separate Docker env files from existing simulator credentials.

Run on the Ubuntu host. Never copy the controller token into an agent container.
Existing identical files are reused; different files are not silently replaced.
"""

import argparse
import json
import os
from pathlib import Path
import re

from simulator.service import validate_auth


ROLE_IDS = {
    "observer": "UAV_observer",
    "leader": "UUV_leader",
    "marker": "USV_marker",
}
ROOT = Path(__file__).parent


def prepare(auth: dict, output_dir: Path) -> list[Path]:
    validate_auth(auth, set(ROLE_IDS.values()))
    contents = {}
    for role, agent_id in ROLE_IDS.items():
        token = auth["agent_tokens"][agent_id]
        # Avoid dotenv expansion of $, quotes or comments in manually supplied tokens.
        if not re.fullmatch(r"[A-Za-z0-9_-]+", token):
            raise ValueError("Use the URL-safe tokens generated by simulator.service --init-auth")
        path = Path(output_dir) / f"{role}.local.env"
        contents[path] = f"SIM_URL=http://ioa-simulator:8090\nSIM_AGENT_TOKEN={token}\n"
    for path, content in contents.items():
        if path.exists() and path.read_text(encoding="utf-8") != content:
            raise FileExistsError(f"{path.name} differs; preserve it and resolve the credential mismatch first")
    Path(output_dir).mkdir(parents=True, exist_ok=True)
    for path, content in contents.items():
        if not path.exists():
            fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
            with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as stream:
                stream.write(content)
        if os.name == "posix":
            path.chmod(0o600)
    return list(contents)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--auth-file", type=Path, default=ROOT / "service_auth.local.json")
    parser.add_argument("--output-dir", type=Path, default=ROOT)
    args = parser.parse_args()
    auth = json.loads(args.auth_file.read_text(encoding="utf-8"))
    for path in prepare(auth, args.output_dir):
        print(f"Ready: {path.name} (one agent identity only; token not printed)")


if __name__ == "__main__":
    main()
