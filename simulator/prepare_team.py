"""Generate the selected five clients, private credentials and Compose wiring.

Run on Ubuntu before starting containers. JSON is also valid YAML, so no extra
dependency is needed. Different existing files are never silently replaced.
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import re

from simulator.scenario import load_scenario
from simulator.service import create_auth_file, validate_auth


ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SCENARIO = ROOT / "simulator/scenarios/five_team.json"


def json_text(value) -> str:
    return json.dumps(value, ensure_ascii=False, indent=2) + "\n"


def prepare_team(root: Path, scenario: Path, model: str = "Qwen3.8-Flash") -> dict:
    root = Path(root)
    env = load_scenario(scenario)
    if env.team_selection is None or len(env.agents) != 5:
        raise ValueError("prepare_team requires a nine-candidate, five-member scenario")
    members = [{"id": a.agent_id, "role": a.role, "carrier_type": a.carrier_type} for a in env.agents]
    ids = [m["id"] for m in members]
    if (any(not re.fullmatch(r"[A-Za-z][A-Za-z0-9_]*", name) for name in ids)
            or len({name.lower() for name in ids}) != len(ids)):
        raise ValueError("client IDs must be distinct ignoring case, using letters, digits and underscores")
    auth_path = root / "simulator/service_auth_five.local.json"
    if not auth_path.exists():
        create_auth_file(auth_path, scenario)
    auth = json.loads(auth_path.read_text(encoding="utf-8"))
    validate_auth(auth, set(ids))
    if any(not re.fullmatch(r"[A-Za-z0-9_-]+", token) for token in auth["agent_tokens"].values()):
        raise ValueError("agent tokens must use the URL-safe format generated by simulator.service")
    leader = next(m["id"] for m in members if m["role"] == "leader")
    observers = "、".join(m["id"] for m in members if m["role"] == "observer")
    markers = "、".join(m["id"] for m in members if m["role"] == "marker")
    descriptions = {
        "observer": f"观测者。实际调用 sim_observe，把目标坐标或未发现结果及 observed_at 经 IoA 报告给 {leader}；按协调指令调用 sim_move_to 设置自身航点。",
        "leader": f"唯一跟踪协调者。等待观测者 {observers} 的真实工具报告，采用最新有效观测协调全部五人。自己在初始化时也必须调用 sim_move_to；之后仅在目的地变化时更新，不能每秒重复分配相同航点任务。等航点任务完成后，让标记者 {markers} 各自调用 sim_try_tag。只使用报告中的目标信息，不预测轨迹。",
        "marker": f"标记者。按 {leader} 的协调指令实际调用 sim_move_to 设置自身航点，在每轮最后调用 sim_try_tag，报告真实 accepted 结果。false 不是工具失败；already_captured 表示其他标记者已成功，正常结束任务，不再重试。",
    }
    common = "只处理任务指定的 episode_id 和 expected_time。工具仅操作自己；不等待位置移动，不推进时钟，不请求其他团队。"
    files = {}
    private_paths = set()
    services = {}
    clients = {}
    for index, member in enumerate(members):
        name, role = member["id"], member["role"]
        slug = name.lower().replace("_", "-")
        service_name = slug
        host_port = 5070 + index
        clients[name] = f"http://127.0.0.1:{host_port}"
        desc = descriptions[role] + common
        config = {
            "server": {"hostname": "ioa-server", "port": 7788},
            "tool_agent": {
                "agent_type": "ReAct", "agent_name": name, "desc": desc,
                "image_name": "react-agent:sim", "container_name": f"capture5-{slug}-tool",
                "port": 7070, "tools_config": f"/app/simulator/tool_configs/{role}.json",
                "model": model, "max_num_steps": 6,
                "rag": {"persist_dir": "", "chunk_size": 512, "llm_model": model,
                        "llm_temperature": 0.1, "similarity_top_k": 2, "data": ""},
            },
            "comm": {
                "name": name, "desc": desc, "type": "Thing Assistant",
                "support_nested_teams": False, "max_team_up_attempts": 3,
                "llm": {"llm_type": "openai-chat", "model": model, "temperature": 0.1},
                "observation_func": "dummy", "discussion_only": False,
            },
        }
        files[root / f"configs/client_configs/cases/capture_five.local/{name}.yaml"] = json_text(config)
        private = root / f"simulator/five_team.local/{name}.env"
        files[private] = "SIM_URL=http://ioa-simulator:8090\nSIM_AGENT_TOKEN=" + auth["agent_tokens"][name] + "\n"
        private_paths.add(private)
        services[service_name] = {
            "image": "ioa-client:sim", "container_name": f"capture5-{slug}-client",
            "env_file": [".env", f"../../simulator/five_team.local/{name}.env"],
            "environment": {"CUSTOM_CONFIG": f"configs/cases/capture_five.local/{name}.yaml"},
            "volumes": ["/var/run/docker.sock:/var/run/docker.sock",
                        f"./volumes/capture_five/{name}/database:/app/database",
                        "../../configs/client_configs:/app/configs:ro"],
            "ports": [f"127.0.0.1:{host_port}:5050"],
            "healthcheck": {
                "test": ["CMD", "python", "-c", "import urllib.request; urllib.request.urlopen('http://127.0.0.1:5050/openapi.json', timeout=3).read()"],
                "interval": "10s", "timeout": "5s", "retries": 12, "start_period": "30s",
            },
        }
    files[root / "dockerfiles/compose/capture_five.local.yaml"] = json_text({
        "services": services,
        "networks": {"default": {"name": "agent_network", "external": True}},
    })
    files[root / "simulator/five_clients.local.json"] = json_text({
        "scenario_id": env.scenario_id, "members": members, "clients": clients,
    })
    files[root / "simulator/five_team.local/selection.json"] = json_text(env.team_selection)
    # Check every conflict before writing the client/configuration files.
    for path, content in files.items():
        if path.exists() and path.read_text(encoding="utf-8") != content:
            raise FileExistsError(f"{path} differs; preserve the old generated files before regenerating")
    for path, content in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists():
            fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600 if path in private_paths else 0o644)
            with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as stream:
                stream.write(content)
        if os.name == "posix" and path in private_paths:
            path.chmod(0o600)
    return {"scenario_id": env.scenario_id, "selected_ids": ids, "clients": clients,
            "files": [str(auth_path), *(str(path) for path in files)]}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--scenario", type=Path, default=DEFAULT_SCENARIO)
    parser.add_argument("--model", default="Qwen3.8-Flash")
    args = parser.parse_args()
    print(json_text(prepare_team(ROOT, args.scenario, args.model)), end="")


if __name__ == "__main__":
    main()
